import os
from phase2_fusion import LiveNCMCoprocessor
from cyberdeck_os import CyberdeckOS
from self_trainer import log_verified_build
import auto_sync

MISSIONS = [
    ("TitanCombatCore", 101, "Implement a 60Hz Rust ECS projectile raycast and hit-detection loop using ARENA_SPAWNS and unlock a Steam 'Sharpshooter' achievement."),
    ("TitanEnemyAI", 204, "Build a Rust ECS tactical enemy patrol and cover-seeking state machine referencing COVER_PILLAR_COUNT and ARENA_OBJECTIVES."),
    ("TitanGrapplePhysics", 309, "Create a Rust 3D momentum-conserving grappling hook and dash cooldown physics solver with coyote-time jump recovery."),
    ("TitanLootEconomy", 415, "Implement a deterministic Rust resource-drop and weapon-upgrade inventory system tied to ARENA_OBJECTIVES."),
    ("TitanMultiplayerSync", 522, "Write a deterministic rollback netcode snapshot buffer in Rust ECS for 4-player arena state synchronization.")
]

def run_batch_factory():
    coproc = LiveNCMCoprocessor()
    deck = CyberdeckOS(cartridge_key="titan_steam", model_id="Qwen/Qwen2.5-Coder-14B-Instruct")

    for project_name, seed_idx, mission in MISSIONS:
        bp = coproc.generate_arena_blueprint(seed_idx=seed_idx)
        proj_dir = f"/kaggle/working/AI_Cyberdeck/{project_name}"
        os.makedirs(f"{proj_dir}/src", exist_ok=True)

        with open(f"{proj_dir}/src/arena_map.rs", "w") as f:
            f.write("// Generated by Stanford NCM Spatial Coprocessor\n" + bp["rust_const"])

        deck.build_titan_steam_game(project_name, mission)

        main_rs_path = f"{proj_dir}/src/main.rs"
        if os.path.exists(main_rs_path):
            with open(main_rs_path, "r") as f:
                log_verified_build(mission, f.read(), proj_dir)

    try:
        from kaggle_secrets import UserSecretsClient
        tok = UserSecretsClient().get_secret("GITHUB_TOKEN")
        auto_sync.setup_auto_git("nike-eng", "Nemotron-NCM", tok)
        auto_sync.sync_now("Batch Swarm Factory: 5 Compiled Game Modules + Verified LoRA Dataset")
    except Exception as e:
        print("GitHub auto-sync note:", e)

if __name__ == "__main__":
    run_batch_factory()
