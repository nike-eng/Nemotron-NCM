import os, gradio as gr
from phase2_fusion import LiveNCMCoprocessor
from ast_memory import ASTCodebaseGraph
from self_trainer import log_verified_build
import auto_sync

coproc = LiveNCMCoprocessor()
ast_graph = ASTCodebaseGraph()

def preview_ncm_and_ast(seed_idx: int):
    bp = coproc.generate_arena_blueprint(seed_idx=int(seed_idx))
    ast_map = ast_graph.build_context_map()
    ncm_display = f"=== NCM PARALLEL SPATIAL MATRIX (Seed #{bp['seed_idx']}) ===\n{bp['raw_grid']}\n\n=== GENERATED RUST CONSTANTS ===\n{bp['rust_const']}"
    return ncm_display, ast_map

def run_cyberdeck_mission(project_name: str, cartridge: str, mission_brief: str, seed_idx: int, auto_github: bool):
    # 1. Generate NCM Arena Blueprint
    bp = coproc.generate_arena_blueprint(seed_idx=int(seed_idx))
    proj_dir = f"/kaggle/working/AI_Cyberdeck/{project_name}"
    os.makedirs(f"{proj_dir}/src", exist_ok=True)
    with open(f"{proj_dir}/src/arena_map.rs", "w") as f:
        f.write("// Generated by Stanford NCM Spatial Coprocessor\n" + bp["rust_const"])

    # 2. Run CyberdeckOS Build if model is loaded in global scope, else run dry-run validation
    try:
        from cyberdeck_os import CyberdeckOS
        global _ACTIVE_DECK
        if "_ACTIVE_DECK" not in globals():
            _ACTIVE_DECK = CyberdeckOS(cartridge_key=cartridge)
        _ACTIVE_DECK.build_titan_steam_game(project_name, mission_brief)
        main_rs = open(f"{proj_dir}/src/main.rs").read()
        log_verified_build(mission_brief, main_rs, proj_dir)
        status = f"COMPILED PASS -> Saved to {proj_dir}/ & logged to LoRA dataset!"
    except Exception as e:
        main_rs = open("/kaggle/working/AI_Cyberdeck/CyberArenaEngine/src/main.rs").read()
        status = f"NCM Blueprint + AST Ready (Load 7B Core in notebook for live synthesis): {e}"

    if auto_github:
        try:
            from kaggle_secrets import UserSecretsClient
            tok = UserSecretsClient().get_secret("GITHUB_TOKEN")
            auto_sync.setup_auto_git("nike-eng", "Nemotron-NCM", tok)
        except Exception:
            pass
        try:
            auto_sync.sync_now(f"Cyberdeck UI Build: {project_name}")
            status += " | Pushed to GitHub!"
        except Exception as ge:
            status += f" | GitHub sync note: {ge}"

    return status, bp["rust_const"], main_rs, ast_graph.build_context_map()

custom_css = """
body, .gradio-container { background-color: #0b0f19 !important; color: #e2e8f0 !important; font-family: monospace; }
h1 { color: #38bdf8 !important; text-shadow: 0 0 10px rgba(56,189,248,0.4); }
"""

with gr.Blocks(css=custom_css, title="AI Cyberdeck OS v1.0") as app:
    gr.Markdown("# ⚡ AI CYBERDECK OS v1.0 — MISSION CONTROL")
    gr.Markdown("**Stanford NCM Spatial Coprocessor • Tree-sitter AST GraphRAG • Self-Healing Rust/WGSL/Steam Compiler**")

    with gr.Row():
        with gr.Column(scale=1):
            project_in = gr.Textbox(label="Project Name", value="CyberArenaEngine")
            cartridge_in = gr.Dropdown(label="Engine Cartridge", choices=["titan_steam", "godot4"], value="titan_steam")
            seed_in = gr.Slider(label="NCM Spatial Seed (0–1999)", minimum=0, maximum=1999, step=1, value=42)
            mission_in = gr.Textbox(
                label="Mission Brief",
                lines=3,
                value="Build a 60Hz Rust ECS tactical arena loop using ARENA_SPAWNS and unlock a Steam achievement."
            )
            github_chk = gr.Checkbox(label="Auto-Commit & Push to GitHub (Triggers Steam CI/CD)", value=True)
            with gr.Row():
                preview_btn = gr.Button("1. Preview NCM + AST", variant="secondary")
                launch_btn = gr.Button("2. Execute Swarm Build", variant="primary")

        with gr.Column(scale=2):
            status_out = gr.Textbox(label="Cyberdeck Telemetry Status", interactive=False)
            with gr.Tabs():
                with gr.Tab("NCM Arena Blueprint"):
                    ncm_out = gr.Code(label="NCM Spatial Tensor & Rust Constants", language="cpp")
                with gr.Tab("Compiled Engine Core"):
                    code_out = gr.Code(label="Verified Engine Source (src/main.rs)", language="cpp")
                with gr.Tab("Tree-sitter AST Map"):
                    ast_out = gr.Textbox(label="Live Repository AST Symbol Map", lines=14)

    preview_btn.click(preview_ncm_and_ast, inputs=[seed_in], outputs=[ncm_out, ast_out])
    launch_btn.click(
        run_cyberdeck_mission,
        inputs=[project_in, cartridge_in, mission_in, seed_in, github_chk],
        outputs=[status_out, ncm_out, code_out, ast_out]
    )

if __name__ == "__main__":
    app.launch(share=True)
